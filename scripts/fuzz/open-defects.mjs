// The open defects: real false positives and false cleans the fuzzer finds and the checker does not fix yet. Keeping them out of the
// generators would hide them, and leaving them in would fail every run, so they are listed (open-defects.json) and held here:
//   - a listed program that still fails is printed by every gate, with its count, and does not fail the run;
//   - a program that fails and is not listed fails the run, as any problem does;
//   - a listed program that no longer fails also fails the run, until its entry leaves the list for rediscovery.json: a fix turns the
//     program green, and the list cannot go stale or pass quietly.
// A grid row is listed by id in open-defects-rows.json, generated from a smoke run at its seed, not by a family of ids: a prefix would hold
// any future defect of that shape. Entries name the families and their cause; only the ledger holds a row.
import { existsSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const OPEN_DEFECTS = join(here, "open-defects.json");
export const OPEN_ROWS = join(here, "open-defects-rows.json");
/** The list with its ledger. A lost ledger throws: without it every family would answer `unlisted` and the gate would be off (R25). */
export function readOpenDefects(path = OPEN_DEFECTS, rows = OPEN_ROWS) {
  if (!existsSync(rows)) throw new Error(`${rows} is missing: it is generated by open-rows.mjs --update and the gates read it`);
  return { ...JSON.parse(readFileSync(path, "utf8")), rows: JSON.parse(readFileSync(rows, "utf8")) };
}

/**
 * The cause of a row the owner's stop rule covers (ADR 0815): it stays listed only while the named uncertifiable it was listed with stands
 * on every run. A checker that lost it, with another U left in the file, would otherwise stay green (R27).
 */
export const STOP_NAMED_U = "R-stop-named-U";
export const namedKey = (finding) => `${finding.id}/${finding.blocker}@${finding.line}:${finding.column}`;

/**
 * The cause of the `flw-owned-*` rows (the scout's F2, an owned edge hides an escape): open defects, certified false cleans among them, with
 * their fix in R5's queue. Listed because the gap is measured and hiding it is no option. It must reach 0 before #173 moves: the final
 * gate (open-rows.mjs --final, `make flip-final`) fails while this cause holds a row.
 */
export const F2_OPEN = "R-F2-open";
/** `flw-guard-yield`: a site past a generator step, its U at the generator: W's F1 places it. Must reach 0 before #173 moves, as F2. */
export const F1_OPEN = "R-F1-open";
export const finalBlockers = (list) => Object.entries(list.rows?.grids ?? {}).flatMap(([grid, rows]) => Object.entries(rows).filter(([, row]) => [F1_OPEN, F2_OPEN].includes(row.cause)).map(([id]) => `${grid}/${id}`));

/** Whether a row answers an entry: same id prefix, code, contexts, source and variant prefix. */
const answers = (entry, row) => String(row.id).startsWith(entry.idPrefix) && entry.code === row.code
  && (!entry.contexts || entry.contexts.includes(row.context)) && (!entry.source || entry.source === row.source) && (!entry.variantPrefix || String(row.variant ?? "").startsWith(entry.variantPrefix));

/** The entry of a grid row (`{ idPrefix, code, variantPrefix?, contexts?, source?, outcome, item }`) with `outcome`, or null. */
export const heldGridEntry = (list, row, outcome) => (list.grids ?? []).find((entry) => answers(entry, row) && entry.outcome === outcome) ?? null;

const JUDGED = ["agree", "clean", "uncertifiable", "recall-gap"];

/**
 * A grid row against the list and the row ledger (open-defects-rows.json, generated: `--update`): the exact failing ids, each with its
 * outcome, `certified` and cause.
 * - `held`: listed, failing the same way;
 * - `moved`: listed, failing another way; `certified`: listed, and now a certified false clean it was not; `fixed`: listed, judged, no
 *   longer failing. Each fails the run;
 * - `unlisted`: failing, not listed, under an entry of that outcome, in a run the ledger does not cover (another sample seed). It is
 *   printed, not failed: `strict` (the ledger's seed, or a ledger that says `complete`) fails it, as any problem;
 * - null: no standing, so a problem fails the run.
 */
export function gridStanding(list, row, problem, { grid, strict = false } = {}) {
  const listed = list.rows?.grids?.[grid]?.[row.id];
  if (problem) {
    if (listed) {
      if (listed.outcome !== problem) return { kind: "moved", listed };
      if (row.detail?.certified === true && !listed.certified) return { kind: "certified", listed };
      if (listed.cause === STOP_NAMED_U && !(row.detail?.namedU ?? []).some((finding) => namedKey(finding) === listed.blocker && (!listed.atRead || finding.atRead === true))) return { kind: "moved", listed };
      return { kind: "held", entry: { item: listed.cause } };
    }
    const entry = heldGridEntry(list, row, problem);
    return entry && !strict ? { kind: "unlisted", entry } : null;
  }
  return listed && JUDGED.includes(row.outcome) ? { kind: "fixed", entry: { item: listed.cause } } : null;
}

/** Whether a run's selection is the ledger's: the same ids, so a failing row off the ledger is new. */
export const ledgerCovers = (list, sampleSeed) => list.rows?.complete === true || (sampleSeed !== null && sampleSeed !== undefined && String(sampleSeed) === String(list.rows?.seed));

/** The ids of a grid's smoke manifest: the same at every seed, so a failing one off the ledger is new whatever the run's sample (R25). */
export function manifestIds(grid) {
  const path = join(here, "smoke", `${grid}.json`);
  return new Set(existsSync(path) ? JSON.parse(readFileSync(path, "utf8")).ids : []);
}

/** Manifest moves the ledger does not account for: a listed row is judged by the ledger, its move from the manifest says nothing new. */
export const offLedger = (list, grid, moves) => moves.filter((move) => !list.rows?.grids?.[grid]?.[move.id]);

/** The ledger's counts: per cause, and its certified and false-positive rows, which a cause's count could hide. */
export function ledgerCounts(rows) {
  const counts = { causes: {}, certified: 0, certifiedF2: 0, falsePositive: 0 };
  for (const grid of Object.values(rows?.grids ?? {})) for (const row of Object.values(grid)) {
    counts.causes[row.cause] = (counts.causes[row.cause] ?? 0) + 1;
    if (row.certified) counts[row.cause === F2_OPEN ? "certifiedF2" : "certified"] += 1;
    if (row.outcome === "false-positive") counts.falsePositive += 1;
  }
  return counts;
}

/** The ledger's counts against the ratchet in open-defects.json: exact, both ways, so a count that moves is an edit in the same diff (R25). */
export function ratchetDifferences(list) {
  const counts = ledgerCounts(list.rows);
  const ratchet = list.ratchet ?? {};
  const out = [];
  for (const key of ["certified", "certifiedF2", "falsePositive"]) if (counts[key] !== ratchet[key]) out.push({ key, rows: counts[key], ratchet: ratchet[key] ?? null });
  for (const cause of new Set([...Object.keys(counts.causes), ...Object.keys(ratchet.causes ?? {})])) if (counts.causes[cause] !== ratchet.causes?.[cause]) out.push({ key: cause, rows: counts.causes[cause] ?? 0, ratchet: ratchet.causes?.[cause] ?? null });
  return out;
}

/** The line every gate prints: what is open, so a green run still says it. */
export function heldLine(grid, entries) {
  const byItem = {};
  for (const entry of entries) byItem[entry.item] = (byItem[entry.item] ?? 0) + 1;
  return `known open ${grid}: ${entries.length} programs still fail (${Object.entries(byItem).map(([item, count]) => `${item} ${count}`).join(", ")}; scripts/fuzz/open-defects.json)`;
}
